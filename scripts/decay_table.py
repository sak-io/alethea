"""Generate docs/architecture/decay-halflives.md (days-to-archive per kind)."""
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from engram import cortex as c  # noqa: E402


def days_to_archive(kind, rate, salience=0.5, limit=3650):
    for day in range(1, limit + 1):
        strength = c.DOWNSCALE_FACTOR ** (rate * day)
        if c.base_activation(kind, strength, salience, day, day) < c.ARCHIVE_ACTIVATION:
            return day
    return None


def main():
    rows = ["# Decay calibration: days until archive (generated)", "",
            "Generated by `scripts/decay_table.py`. Unreinforced memory, factor 0.93 per",
            "downscale period, archive below %.1f. Salience 0.5 / 0.2 / 0.8." % c.ARCHIVE_ACTIVATION,
            "Recency term: `0.3*exp(-days_since_last_access/7)` (0.3 at day 0, ~0.11 at day 7).", "",
            "| kind | d | uniform 0.93 (s=.5/.2/.8) | per-kind (s=.5/.2/.8) | per-kind rate/day |",
            "|---|---|---|---|---|"]
    for k in ("episodic", "semantic", "procedural", "identity"):
        def cell(tbl):
            return "/".join(str(days_to_archive(k, tbl[k], s) or "never") for s in (0.5, 0.2, 0.8))
        rows.append("| %s | %s | %s | %s | %s |" % (k, c.DECAY[k], cell(c.UNIFORM_RATE),
                                                   cell(c.DOWNSCALE_RATE), c.DOWNSCALE_RATE[k]))
    rows += ["", "Shipped default: per-kind (`DOWNSCALE_RATE`, ADR 0003 item 4, owner approved)."]
    out = Path(__file__).resolve().parent.parent / "docs/architecture/decay-halflives.md"
    out.write_text("\n".join(rows) + "\n")
    print("\n".join(rows))


if __name__ == "__main__":
    main()
