"""Sync-back (R25): render durable memories into host rule files. Stdlib only.

Two halves with a hard trust boundary:

* DAEMON half (`select_items`): pure read + render. Takes a repo_root string, returns plain
  text items. It never receives or uses a path, target or directory and never writes a file.
* CLIENT half (`run`, `write_target`): runs in the caller's own process (mnemo, or a detached
  child of the hook). It derives every path from the caller's own git root (`gitctx`), asks
  the daemon for items, re-sanitises them, and writes the files atomically.

The output flows into always-on prompts (CLAUDE.md `@.claude/alethea_learned.md` import,
Cursor alwaysApply rule), so memory is DATA: every line goes through `render` (plain list
items) under `render.RECALL_HEADER`; frontmatter and headers are fixed text, never memory.

Selection redaction policy: stored text is already masked at encode time, so such items are
exported with their [REDACTED:...] markers as stored. An item is SKIPPED (not rewritten) only
when the redactor would still change the stored text (a secret that older redaction missed).
"""
import errno
import os
import stat
import sys
import time

from alethea import gitctx, render
from alethea.redact import redact

MAX_ITEMS = 20
MAX_BYTES = 4096          # whole generated file, headers included
ITEM_MAX_CHARS = 300
MARKER = "alethea-auto-generated"
TARGETS = {
    "claude": (".claude", "alethea_learned.md"),
    "cursor": (".cursor/rules", "alethea_learned.mdc"),
}
GENERATED = "Generated at "
FRONTMATTER = ("---\n"
               "description: Alethea learned project memory (auto-generated, do not edit)\n"
               "alwaysApply: true\n"
               "---\n")
GITIGNORE_COMMENT = "# Alethea generated memory export (commit only if you choose to share it)"
FORBIDDEN_PARAMS = ("path", "paths", "target", "targets", "dir", "directory", "file", "output")

STALE_TMP_S = 60.0
_before_rename = None  # test hook: called between temp write and rename


# ---------------------------------------------------------------- shared rendering

def item_text(text):
    """One safe list item ('- ...') or '' . `@` is neutralised: Claude Code expands @path
    imports found in imported files, so a memory must not be able to pull a file in."""
    line = render.list_item(text, ITEM_MAX_CHARS)
    if not line:
        return ""
    line = line.replace("@", "＠")
    if MARKER in line.lower():  # cannot forge or imitate the ownership header
        return ""
    return line


def head_lines(target):
    return ((FRONTMATTER if target == "cursor" else "") +
            "<!-- %s: do not edit. Regenerated by `mnemo export-rules`; "
            "identity memories are never exported. -->\n" % MARKER)


def build_file(items, target, now):
    """Full file text. `items` are raw strings (re-sanitised here). Caps: MAX_ITEMS items,
    MAX_BYTES total."""
    stamp = GENERATED + time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(now)) + "\n"
    head = head_lines(target) + stamp + "\n" + render.RECALL_HEADER + "\n"
    out, n = head, 0
    for raw in items[:MAX_ITEMS * 4] if isinstance(items, list) else []:
        if n >= MAX_ITEMS:
            break
        line = item_text(raw if isinstance(raw, str) else "")
        if not line:
            continue
        if len((out + line + "\n").encode("utf-8")) > MAX_BYTES:
            break
        out += line + "\n"
        n += 1
    if n == 0:
        out += "(no durable memories for this repository yet)\n"
    return out


def stable_body(text):
    """File text without the generation-time line (idempotence comparison)."""
    return "".join(ln for ln in text.splitlines(True) if not ln.startswith(GENERATED))


def is_ours(text, target):
    return text.startswith(head_lines(target))


# ---------------------------------------------------------------- daemon half

def valid_repo_root(v):
    return (isinstance(v, str) and 0 < len(v) <= 4096 and "\0" not in v
            and os.path.isabs(v) and ".." not in v.split("/"))


def select_items(cortex, repo_root, now=None):
    """Plain item strings (no '- ' prefix) for repo_root. Read-only; caller holds the lock."""
    now = cortex.clock() if now is None else now
    rows = cortex.db.execute(
        "SELECT id FROM memories WHERE status='active' AND kind IN ('semantic','procedural') "
        "AND repo_root=?", (repo_root,)).fetchall()
    mems = cortex.get_many([r[0] for r in rows])
    ranked = []
    for m in mems.values():
        meta = m.get("meta") or {}
        if not (m["access_count"] >= 2 or meta.get("deliberate") is True):
            continue
        ranked.append((-cortex.activation(m, now), m["id"], m))
    ranked.sort(key=lambda t: t[:2])
    out, size = [], 0
    for _, _, m in ranked:
        raw = " ".join((m.get("gist") or m["content"] or "").split())
        if redact(raw) != raw or redact(m["content"] or "") != (m["content"] or ""):
            continue  # policy: skip when redaction would still change it (see module doc)
        line = item_text(raw)
        if not line:
            continue
        size += len(line.encode("utf-8")) + 1
        if len(out) >= MAX_ITEMS or size > MAX_BYTES:
            break
        out.append(line[2:])
    return out


# ---------------------------------------------------------------- client half

class Refused(Exception):
    pass


def _open_dir(parent_fd, name, create):
    try:
        st = os.stat(name, dir_fd=parent_fd, follow_symlinks=False)
    except FileNotFoundError:
        if not create:
            raise
        os.mkdir(name, 0o755, dir_fd=parent_fd)
    else:
        if stat.S_ISLNK(st.st_mode):
            raise Refused("%s is a symlink" % name)
        if not stat.S_ISDIR(st.st_mode):
            raise Refused("%s is not a directory" % name)
    try:
        return os.open(name, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=parent_fd)
    except OSError as e:
        if e.errno in (errno.ELOOP, errno.ENOTDIR):
            raise Refused("%s is a symlink" % name)
        raise


def _read_existing(dfd, name):
    """Text of the target, or None if absent. Refuses symlinks and non-regular files."""
    try:
        st = os.stat(name, dir_fd=dfd, follow_symlinks=False)
    except FileNotFoundError:
        return None
    if not stat.S_ISREG(st.st_mode):
        raise Refused("%s is a symlink or not a regular file" % name)
    try:
        fd = os.open(name, os.O_RDONLY | os.O_NOFOLLOW, dir_fd=dfd)
    except OSError as e:
        if e.errno == errno.ELOOP:
            raise Refused("%s is a symlink" % name)
        raise
    with os.fdopen(fd, "rb") as f:
        return f.read(MAX_BYTES * 4).decode("utf-8", "replace")


def _sweep_stale_tmp(dfd, name):
    """Remove our own leftover temp files (.<name>.tmp<digits>) older than STALE_TMP_S."""
    prefix = ".%s.tmp" % name
    try:
        names = os.listdir(dfd)
    except OSError:
        return
    for n in names:
        if not (n.startswith(prefix) and n[len(prefix):].isdigit()):
            continue
        try:
            st = os.stat(n, dir_fd=dfd, follow_symlinks=False)
            if stat.S_ISREG(st.st_mode) and time.time() - st.st_mtime > STALE_TMP_S:
                os.unlink(n, dir_fd=dfd)
        except OSError:
            pass


def write_target(root, target, items, now, create=True):
    """Write one target under `root`. Returns 'written' | 'unchanged' | 'skipped'.
    Raises Refused (symlink / foreign file) or OSError."""
    rel_dir, name = TARGETS[target]
    rfd = os.open(root, os.O_RDONLY | os.O_DIRECTORY)
    fds = [rfd]
    try:
        cur = rfd
        for part in rel_dir.split("/"):
            try:
                cur = _open_dir(cur, part, create)
            except FileNotFoundError:
                return "skipped"
            fds.append(cur)
        _sweep_stale_tmp(cur, name)
        existing = _read_existing(cur, name)
        if existing is None and not create:
            return "skipped"
        if existing is not None and not is_ours(existing, target):
            raise Refused("%s/%s exists and lacks the Alethea header; not overwriting"
                          % (rel_dir, name))
        text = build_file(items, target, now)
        if existing is not None and stable_body(existing) == stable_body(text):
            return "unchanged"
        tmp = ".%s.tmp%d" % (name, os.getpid())
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o644,
                     dir_fd=cur)
        try:
            with os.fdopen(fd, "wb") as f:
                f.write(text.encode("utf-8"))
                f.flush()
                os.fsync(f.fileno())
            if _before_rename:
                _before_rename()
            os.rename(tmp, name, src_dir_fd=cur, dst_dir_fd=cur)
        except BaseException:
            try:
                os.unlink(tmp, dir_fd=cur)
            except OSError:
                pass
            raise
        try:
            os.fsync(cur)
        except OSError:
            pass
        return "written"
    finally:
        for fd in fds:
            try:
                os.close(fd)
            except OSError:
                pass


def ensure_gitignore(root, targets):
    """Append missing generated paths to root/.gitignore. Returns warning text or ''."""
    want = []
    for t in targets:
        want.append("%s/%s" % TARGETS[t])
        want.append("%s/.%s.tmp*" % (TARGETS[t][0], TARGETS[t][1]))
    path = os.path.join(root, ".gitignore")
    try:
        existing = ""
        try:
            st = os.lstat(path)
            if not stat.S_ISREG(st.st_mode):
                return ".gitignore is not a regular file; add %s yourself" % ", ".join(want)
            with open(path, "r", encoding="utf-8", errors="replace", newline="") as f:
                existing = f.read()
        except FileNotFoundError:
            pass
        have = {ln.strip().lstrip("/") for ln in existing.splitlines()}
        missing = [w for w in want if w not in have]
        if not missing:
            return ""
        eol = "\r\n" if "\r\n" in existing else "\n"
        add = ("" if not existing or existing.endswith("\n") else eol)
        add += GITIGNORE_COMMENT + eol + "".join(w + eol for w in missing)
        fd = os.open(path, os.O_WRONLY | os.O_APPEND | os.O_CREAT | os.O_NOFOLLOW, 0o644)
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as f:
            f.write(add)
        return ""
    except OSError:
        return ".gitignore is not writable; add %s yourself so memories are not committed" % (
            ", ".join(want))


def run(cwd, targets=("claude", "cursor"), if_changed=False, env=None, now=None,
        timeout=None):
    """Export for the git root of cwd. Never raises. Returns a dict:
    {"ok", "offline"?, "error"?, "results": {target: status}, "warnings": [..], "refused": bool}
    if_changed: only refresh existing Alethea-owned targets (no new files, no .gitignore edit)."""
    from alethea import client
    res = {"ok": True, "results": {}, "warnings": [], "refused": False}
    try:
        root = gitctx.repo_root(cwd)
        if not root:
            return dict(res, ok=False, error="not inside a git repository")
        if if_changed and not any(
                _exists(root, t) for t in targets):
            return dict(res, results={t: "skipped" for t in targets})
        r = client.call("export_rules", {"repo_root": root},
                        timeout=timeout or client.TIMEOUT_CLI, env=env)
        if r.get("offline"):
            return dict(res, ok=False, offline=True)
        if not r.get("ok"):
            return dict(res, ok=False, error=str(r.get("error") or "export failed"))
        items = r.get("items")
        items = items if isinstance(items, list) else []
        now = time.time() if now is None else now
        for t in targets:
            try:
                res["results"][t] = write_target(
                    root, t, items, now, create=not if_changed)
            except Refused as e:
                res["results"][t] = "refused"
                res["refused"] = True
                res["warnings"].append(str(e))
            except OSError as e:
                res["results"][t] = "error"
                res["ok"] = False
                res["error"] = "cannot write %s: %s" % (t, e.strerror or type(e).__name__)
        if not if_changed:
            done = [t for t in targets if res["results"].get(t) in ("written", "unchanged")]
            w = ensure_gitignore(root, done) if done else ""
            if w:
                res["warnings"].append(w)
        return res
    except Exception as e:
        return dict(res, ok=False, error="export failed: %s" % type(e).__name__)


def _exists(root, target):
    rel_dir, name = TARGETS[target]
    return os.path.lexists(os.path.join(root, rel_dir, name))


def main(argv=None):
    """Detached entry point for the hook: refresh existing targets, silently."""
    argv = sys.argv[1:] if argv is None else argv
    cwd = argv[0] if argv else os.getcwd()
    run(cwd, if_changed=True, timeout=5.0)
    return 0


if __name__ == "__main__":
    sys.exit(main())
